/**
 * Transforms the Panam specification catalog into active application GlossaryItems,
 * complete with generated variant matrices so selecting ANY size or material
 * recalibrates the price instantaneously.
 */
export function getPanamGlossaryItems(): GlossaryItem[] {
  return PANAM_FITTINGS_VALVES_JOINTS_CATALOG.map((spec) => {
    const defaultMat = spec.availableMaterials[0] || 'CPVC';
    const defaultSz = spec.availableSizes.includes('3/4 inch')
      ? '3/4 inch'
      : spec.availableSizes[0] || '3/4 inch';

    const matrix = generateVariantMatrix(
      spec.baseRate3_4CPVCPaise,
      spec.availableMaterials,
      spec.availableSizes
    );

    const defaultRate = getVariantPricePaise(
      {
        id: 'tmp',
        category: spec.category,
        name: spec.name,
        sizeSpec: `${defaultSz} (${defaultMat})`,
        unit: spec.unit,
        defaultRatePaise: spec.baseRate3_4CPVCPaise,
        taxRate: spec.taxRate,
        active: true,
        variantPrices: matrix,
      },
      defaultMat,
      defaultSz
    );

    return {
      id: `panam-${spec.code.toLowerCase()}`,
      category: spec.category,
      name: spec.name,
      sizeSpec: `${defaultSz} (${defaultMat})`,
      unit: spec.unit,
      defaultRatePaise: defaultRate,
      taxRate: spec.taxRate,
      active: true,
      hasVariants: true,
      availableMaterials: spec.availableMaterials,
      availableSizes: spec.availableSizes,
      variantPrices: matrix,
      notes: `${spec.subcategory} · ${spec.function} (${spec.applicableStandards || 'Std'})`,
    };
  });
}
